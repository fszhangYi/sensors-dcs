def catalog_json() -> str:
    """JSON blob for injection into HTML (compact)."""
    return json.dumps(PAGE_STRINGS, ensure_ascii=False, separators=(",", ":"))


def assert_parity() -> None:
    zh = set(PAGE_STRINGS["zh"])
    en = set(PAGE_STRINGS["en"])
    if zh != en:
        missing_en = sorted(zh - en)
        missing_zh = sorted(en - zh)
        raise AssertionError(f"i18n key parity failed en_missing={missing_en} zh_missing={missing_zh}")


def inject_i18n_json(html: str, *, marker: str = "__DCS_I18N_JSON__") -> str:
    """Replace marker token with JSON catalog (safe inside a JS string literal)."""
    assert_parity()
    # Escape for embedding inside a single-quoted JS string via JSON.parse
    payload = catalog_json().replace("</", "<\\/")
    if marker not in html:
        return html
    return html.replace(marker, payload)


def i18n_boot_script() -> str:
    """Shared JS: t / applyDomI18n / locale toggle helpers. Expects DCS_I18N global."""
    return ""
